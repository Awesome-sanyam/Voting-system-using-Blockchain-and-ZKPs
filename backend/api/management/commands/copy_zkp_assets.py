"""
Management command: copy_zkp_assets
────────────────────────────────────────────────────────────────────────────────
Copies compiled ZKP circuit artifacts from the blockchain build directory into
Django's static files directory so they can be served by the dev server or
collected by `collectstatic` for production.

Required files (generated by compile_circuit.sh / snarkJS):
  - blockchain/circuits/build/voter_eligibility_js/voter_eligibility.wasm
  - blockchain/circuits/build/voter_eligibility_final.zkey
  - blockchain/circuits/build/verification_key.json

Target (expected by zkp_prover.js CRYPTO_CONFIG):
  - backend/api/static/api/crypto/voter_eligibility.wasm
  - backend/api/static/api/crypto/voter_eligibility_final.zkey
  - backend/api/static/api/crypto/verification_key.json

Usage:
    cd backend && python manage.py copy_zkp_assets
"""

import shutil
from pathlib import Path
from django.core.management.base import BaseCommand


class Command(BaseCommand):
    help = "Copy compiled ZKP WASM/zkey artifacts into Django static files."

    def handle(self, *args, **options):
        # File: backend/api/management/commands/copy_zkp_assets.py
        # parents[0] = commands/  parents[1] = management/  parents[2] = api/
        # parents[3] = backend/   parents[4] = Capstone-2/  (repo root)
        backend_dir = Path(__file__).resolve().parents[3]  # backend/
        repo_root = backend_dir.parent                     # Capstone-2/

        dest_dir = backend_dir / "api" / "static" / "api" / "crypto"
        dest_dir.mkdir(parents=True, exist_ok=True)

        sources = {
            "voter_eligibility.wasm": repo_root / "blockchain" / "circuits" / "build" / "voter_eligibility_js" / "voter_eligibility.wasm",
            "voter_eligibility_final.zkey": repo_root / "blockchain" / "circuits" / "build" / "voter_eligibility_final.zkey",
            "verification_key.json": repo_root / "blockchain" / "circuits" / "build" / "verification_key.json",
        }

        all_ok = True
        for filename, source in sources.items():
            dest = dest_dir / filename
            if not source.exists():
                self.stderr.write(self.style.ERROR(
                    f"  [MISSING] {source}\n"
                    f"           Run blockchain/scripts/compile_circuit.sh first."
                ))
                all_ok = False
                continue

            shutil.copy2(source, dest)
            size_kb = dest.stat().st_size // 1024
            self.stdout.write(self.style.SUCCESS(
                f"  [OK] {filename} ({size_kb} KB) → {dest.relative_to(backend_dir)}"
            ))

        if all_ok:
            self.stdout.write(self.style.SUCCESS(
                "\nAll ZKP assets copied. Run `python manage.py collectstatic` for production."
            ))
        else:
            self.stdout.write(self.style.WARNING(
                "\nSome assets were missing. SnarkJS will fall back to mock proof generation."
            ))
